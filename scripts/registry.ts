/**
 * Plugin registry generator.
 *
 *   bun scripts/registry.ts
 *
 * A plugin is a folder in plugins/ with a plugin.ts. The browser bundle needs static imports, so this script writes
 * them to plugins/registry.gen.ts in alphabetical order. Nobody edits a shared list to add a plugin, so plugins added
 * in parallel never conflict, and the rail, palette and Briefing order themselves from what each plugin declares.
 *
 * Private plugins live in private/plugins/ (see private/README.md) and are not part of the everyday app. They join the
 * registry only when VANTAGE_LOCAL=1 and VANTAGE_PRIVATE=1, so a plain `bun run dev` never imports, bundles or serves them.
 *
 * It runs after `bun install`, as the first step of `bun run check`, when the server starts (before a production
 * build), and from the development server whenever a plugin folder appears or goes.
 */
import { rename } from "node:fs/promises";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const PLUGINS_DIR = join(ROOT, "plugins");
const PRIVATE_DIR = join(ROOT, "private", "plugins");
const OUT = join(PLUGINS_DIR, "registry.gen.ts");
const PLUGIN_ID = /^[a-z][a-z0-9-]*$/;

/** Host and LAN features are opt-in, including the separate private tree. */
export const localEnabled = (): boolean => process.env.VANTAGE_LOCAL === "1";
export const privateEnabled = (): boolean => localEnabled() && process.env.VANTAGE_PRIVATE === "1";

/** A local-only marker keeps host and LAN code out of both discovery paths before it can run. */
export async function pluginEnabled(dir: string): Promise<boolean> {
  return localEnabled() || !(await Bun.file(join(dir, "local-only")).exists());
}

/** "zz-test" → "zzTestPlugin". The suffix keeps ids such as "new" from becoming reserved words. */
const binding = (id: string): string => `${id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Plugin`;

/** Every plugin in this build: its id and the import specifier the registry writes, relative to plugins/. */
export async function pluginEntries(includeLocal = false): Promise<{ id: string; spec: string }[]> {
  const entries: { id: string; spec: string }[] = [];
  const collect = async (dir: string, prefix: string): Promise<void> => {
    for await (const rel of new Bun.Glob("*/plugin.ts").scan({ cwd: dir })) {
      const id = rel.split("/")[0] ?? "";
      if (includeLocal || await pluginEnabled(join(dir, id))) entries.push({ id, spec: `${prefix}${id}/plugin` });
    }
  };
  await collect(PLUGINS_DIR, "./");
  if (privateEnabled()) await collect(PRIVATE_DIR, "../private/plugins/");

  const seen = new Set<string>();
  const bindings = new Map<string, string>();
  for (const { id } of entries) {
    if (!PLUGIN_ID.test(id)) throw new Error(`Plugin folder "${id}" must be lowercase letters, digits and dashes`);
    if (seen.has(id)) throw new Error(`Plugin "${id}" is declared in two folders; plugin ids must be unique`);
    seen.add(id);
    const other = bindings.get(binding(id));
    if (other && other !== id) throw new Error(`Plugin folders "${other}" and "${id}" differ only by dashes; rename one`);
    bindings.set(binding(id), id);
  }
  return entries.sort((a, b) => a.id.localeCompare(b.id));
}

/** Ids of the plugin folders in this build, sorted by name. */
export async function pluginIds(): Promise<string[]> {
  return (await pluginEntries()).map((entry) => entry.id);
}

function render(entries: readonly { id: string; spec: string }[], ids: readonly string[]): string {
  return [
    "// Generated by scripts/registry.ts from available plugin folders. Host/LAN plugins require VANTAGE_LOCAL=1. Do not edit.",
    'import type { Plugin } from "../app/core/plugin";',
    ...entries.map(({ id, spec }) => `import ${binding(id)} from "${spec}";`),
    "",
    "export const plugins = [",
    ...entries.map(({ id }) => `  ${binding(id)},`),
    "] as const satisfies readonly Plugin[];",
    "",
    `export const localEnabled = ${localEnabled()};`,
    `export type PluginId = ${ids.map((id) => JSON.stringify(id)).join(" | ")};`,
    "",
  ].join("\n");
}

/** Write plugins/registry.gen.ts. Leaves the file alone when nothing changed, so watchers do not reload for nothing. */
export async function writeRegistry(): Promise<{ ids: string[]; changed: boolean }> {
  const entries = await pluginEntries();
  const ids = entries.map((entry) => entry.id);
  const source = render(entries, (await pluginEntries(true)).map((entry) => entry.id));
  const file = Bun.file(OUT);
  if ((await file.exists()) && (await file.text()) === source) return { ids, changed: false };
  // Write beside the file and rename, so the bundler never reads a half-written registry.
  const temp = `${OUT}.${process.pid}.tmp`;
  await Bun.write(temp, source);
  await rename(temp, OUT);
  return { ids, changed: true };
}

if (import.meta.main) {
  const { ids, changed } = await writeRegistry();
  console.log(`Plugin registry ${changed ? "written" : "up to date"} · ${ids.length} plugins${privateEnabled() ? " (private on)" : ""}`);
}
